//! Combat resolution calculator.
//!
//! Resolves an attack from an attacker unit against a defender unit,
//! applying special rules at the appropriate phases of the combat sequence.
//!
//! ## Combat Sequence & Rule Hook Points
//! 1. Attack count          - Impact(X)
//! 2. Hit roll setup        - Reliable, Artillery, Indirect, Thrust, Stealth
//! 3. Hit roll resolution   - Furious, Relentless, Surge, Rending
//! 4. Hit multiplication    - Blast(X)
//! 5. Defense roll setup    - AP(X)
//! 6. Defense roll resolve  - Bane, Unstoppable
//! 7. Wound application     - Deadly(X), Tough(X)
//! 8. Regeneration          - Regeneration (skipped by Bane/Rending/Unstoppable)

use crate::combat::context::CombatContext;
use crate::combat::dice;
use crate::models::rules::SpecialRule;
use crate::models::unit::Unit;
use crate::models::weapons::Weapon;

/// Detailed breakdown of a single attack resolution.
#[derive(Debug, Clone, Default, serde::Serialize, serde::Deserialize)]
pub struct AttackResult {
    /// Name of the weapon that made the attack
    pub weapon_name: String,
    /// Base number of attacks rolled
    pub base_attacks: u32,
    /// Extra attacks generated by special rules (Furious, Surge, etc.)
    pub extra_attacks: u32,
    /// Hits scored before multiplication
    pub hits_before_multiplier: u32,
    /// Hits after Blast multiplication
    pub total_hits: u32,
    /// Hits blocked by the defender
    pub blocked_hits: u32,
    /// Wounds actually inflicted (after Deadly/Tough)
    pub wounds_inflicted: u32,
    /// Wounds ignored by Regeneration
    pub regenerated_wounds: u32,
    /// Net wounds after regeneration
    pub net_wounds: u32,
}

/// Overall result of resolving an attacker against a defender.
#[derive(Debug, Clone, Default, serde::Serialize, serde::Deserialize)]
pub struct CombatResult {
    /// Per-weapon breakdowns
    pub attacks: Vec<AttackResult>,
    /// Total net wounds dealt to the defender
    pub total_net_wounds: u32,
    /// Total models removed from the defender
    pub models_removed: u32,
}

/// Resolve the attacks of `attacker` against `defender` under the given
/// combat context. This is the top-level entry point for the calculator.
///
/// # Errors
/// Returns an error string if the attack configuration is invalid.
pub fn resolve_attack(
    attacker: &Unit,
    defender: &Unit,
    context: &CombatContext,
) -> Result<CombatResult, String> {
    let mut result = CombatResult::default();

    let weapons: Vec<&Weapon> = select_weapons(attacker, context);

    // Phase 1: Impact(X) — extra dice on a charge unless fatigued
    if context.is_melee()
        && context.is_charging
        && !context.attacker_fatigued
        && let Some(impact) = resolve_impact(attacker, defender)
    {
        result.total_net_wounds = result.total_net_wounds.saturating_add(impact.net_wounds);
        result.attacks.push(impact);
    }

    for weapon in weapons {
        let attack = resolve_weapon_attack(attacker, weapon, defender, context)?;
        result.total_net_wounds = result.total_net_wounds.saturating_add(attack.net_wounds);
        result.attacks.push(attack);
    }

    result.models_removed = compute_models_removed(defender, result.total_net_wounds);

    Ok(result)
}

/// Resolve a single weapon's attacks against the defender.
///
/// The `Result` is retained for API symmetry with [`resolve_attack`]; future
/// rule validation (e.g. Impact resolution) may introduce error paths.
#[allow(clippy::unnecessary_wraps)]
fn resolve_weapon_attack(
    attacker: &Unit,
    weapon: &Weapon,
    defender: &Unit,
    context: &CombatContext,
) -> Result<AttackResult, String> {
    let mut attack = AttackResult {
        weapon_name: weapon.name.clone(),
        base_attacks: u32::from(weapon.total_attacks()),
        ..AttackResult::default()
    };

    // Phase 1: Attack count (Impact(X) would add dice here on a charge)
    // TODO: Resolve Impact(X)

    // Phase 2: Hit roll setup (modify Quality target)
    let hit_modifier = compute_hit_modifier(attacker, context);
    let quality_target = effective_quality(weapon, attacker, context);

    // Phase 3: Hit roll resolution
    let hit_rolls = dice::roll_d6s(attack.base_attacks, hit_modifier);
    let mut hits = dice::count_successes(&hit_rolls, quality_target);

    // Extra hits from Furious/Surge/Relentless on unmodified 6s
    // (checked on both the weapon and the unit, since upgrades like
    // Combat Bio-Engineer grant Furious at unit level)
    let extra_hits = count_extra_hits(&hit_rolls, weapon, attacker, context);
    attack.extra_attacks = extra_hits;
    hits = hits.saturating_add(extra_hits);
    attack.hits_before_multiplier = hits;

    // Rending: hits scored on unmodified 6s (original hits only — extras
    // don't count as 6s) block at AP(+4). Split before Blast so copies
    // of a rending hit keep the property.
    let six_count: u32 = hit_rolls
        .iter()
        .filter(|r| r.is_unmodified_six())
        .count()
        .try_into()
        .unwrap_or(u32::MAX);
    let rending_hits = if weapon.special_rules.contains(&SpecialRule::Rending) {
        six_count.min(hits)
    } else {
        0
    };
    let normal_hits = hits.saturating_sub(rending_hits);

    // Phase 4: Blast(X) hit multiplication (uniform across both pools)
    let rending_total = apply_blast(rending_hits, weapon, defender.quantity);
    let normal_total = apply_blast(normal_hits, weapon, defender.quantity);
    let total_hits = rending_total.saturating_add(normal_total);
    attack.total_hits = total_hits;

    // Phase 5: Defense roll setup (AP modifies the defense target)
    let defense_target = effective_defense(weapon, defender, context);

    // Phase 6: Defense roll resolution (Bane rerolls 6s, Rending +4 pool,
    // Shred extra wounds on 1s)
    let (blocked, shred_wounds) = roll_defense(rending_total, normal_total, defense_target, weapon);
    attack.blocked_hits = blocked;

    let failed_blocks = total_hits.saturating_sub(blocked);

    // Phase 7: Wound application (Deadly(X) multiplies wounds; Shred adds)
    let wounds = apply_deadly(failed_blocks, weapon).saturating_add(shred_wounds);
    attack.wounds_inflicted = wounds;

    // Phase 8: Regeneration (skipped if weapon ignores regen)
    let (net_wounds, regenerated) = apply_regeneration(wounds, defender, &weapon.special_rules);
    attack.regenerated_wounds = regenerated;
    attack.net_wounds = net_wounds;

    Ok(attack)
}

/// Weapons the attacker can use in this context.
///
/// Versatile Attack lets the unit choose any of its weapons whether
/// striking in melee or shooting; everyone else is limited to weapons
/// matching the context type.
#[must_use]
fn select_weapons<'a>(attacker: &'a Unit, context: &CombatContext) -> Vec<&'a Weapon> {
    if attacker.has_rule(&SpecialRule::VersatileAttack) {
        attacker.weapons.iter().collect()
    } else if context.is_melee() {
        attacker.melee_weapons()
    } else {
        attacker.ranged_weapons()
    }
}

/// Compute the total modifier to apply to hit rolls.
///
/// Battleborn: +1 to hit rolls when attacking in melee.
fn compute_hit_modifier(attacker: &Unit, context: &CombatContext) -> i32 {
    // Indirect (shooting after moving), Thrust (charging) and Stealth
    // (defender at >9") would add further modifiers here.
    // TODO: Implement those rule modifiers.
    if context.is_melee() && attacker.has_rule(&SpecialRule::Battleborn) {
        return 1;
    }
    0
}

/// Determine the effective Quality target for hit rolls.
/// Reliable forces Quality 2+.
fn effective_quality(weapon: &Weapon, attacker: &Unit, context: &CombatContext) -> u8 {
    // Fatigued units only hit on unmodified 6
    if context.attacker_fatigued {
        return 6;
    }

    // Reliable: this weapon attacks at Quality 2+
    if weapon.special_rules.contains(&SpecialRule::Reliable) {
        return 2;
    }

    attacker.quality
}

/// Count extra hits generated by Furious/Surge/Relentless on unmodified 6s.
/// Rules are checked on both the weapon and the attacking unit, since
/// upgrades can grant these rules at either level.
fn count_extra_hits(
    hit_rolls: &[dice::DieRoll],
    weapon: &Weapon,
    attacker: &Unit,
    context: &CombatContext,
) -> u32 {
    let sixes = hit_rolls.iter().filter(|r| r.is_unmodified_six()).count();

    let generates_extras = weapon
        .special_rules
        .iter()
        .chain(attacker.special_rules.iter())
        .any(|rule| rule_is_active_extra_hit(rule, context));

    if generates_extras {
        sixes.try_into().unwrap_or(u32::MAX)
    } else {
        0
    }
}

/// Whether an extra-hit-on-six rule is active given the combat context.
fn rule_is_active_extra_hit(rule: &SpecialRule, context: &CombatContext) -> bool {
    match rule {
        // Furious only triggers when charging in melee
        SpecialRule::Furious => context.is_charging && context.is_melee(),
        // Relentless only triggers at long range (ranged)
        SpecialRule::Relentless => context.is_ranged() && context.is_long_range(),
        // Surge triggers on any unmodified 6
        SpecialRule::Surge => true,
        _ => false,
    }
}

/// Apply Blast(X) multiplication, capped by the defender's model count.
fn apply_blast(hits: u32, weapon: &Weapon, defender_quantity: u8) -> u32 {
    let multiplier = weapon
        .special_rules
        .iter()
        .find_map(SpecialRule::blast_multiplier);

    match multiplier {
        Some(m) if m > 1 => {
            // Each hit is multiplied by X, but total capped by models in target
            let per_hit_cap = u32::from(m);
            let capped_multiplier = per_hit_cap.min(u32::from(defender_quantity));
            hits.saturating_mul(capped_multiplier)
        }
        _ => hits,
    }
}

/// Determine the effective Defense target, applying AP and cover.
fn effective_defense(weapon: &Weapon, defender: &Unit, context: &CombatContext) -> u8 {
    let mut defense = i32::from(defender.defense);

    // Cover: +1 to the defender's rolls vs shooting, so the defender
    // needs 1 LESS to block. (AP by contrast subtracts from the rolls,
    // so the target goes UP.)
    if context.is_ranged() && context.defender_in_cover {
        defense = defense.saturating_sub(1);
    }

    // Shielded: +1 to the defender's rolls in any context, so the
    // defender needs 1 LESS to block.
    if defender.has_rule(&SpecialRule::Shielded) {
        defense = defense.saturating_sub(1);
    }

    // AP(X): Target needs X higher to defend
    if let Some(ap) = weapon.get_ap() {
        defense = defense.saturating_add(i32::from(ap));
    }

    // Rending: unmodified 6 to hit gains AP(+4) — handled per-hit, placeholder
    // TODO: integrate Rending AP boost into the defense rolls for those hits

    // Clamp to valid range 2..=6 (a roll of 6 always succeeds regardless)
    defense.clamp(2, 6).try_into().unwrap_or(6)
}

/// Apply Deadly(X) wound multiplication.
fn apply_deadly(failed_blocks: u32, weapon: &Weapon) -> u32 {
    let multiplier = weapon
        .special_rules
        .iter()
        .find_map(SpecialRule::deadly_multiplier);

    match multiplier {
        Some(m) if m > 1 => failed_blocks.saturating_mul(u32::from(m)),
        _ => failed_blocks,
    }
}

/// Roll defense for the two hit pools and return `(blocked, shred_wounds)`.
/// The rending pool blocks at defense+4 (cap 6); Bane rerolls unmodified
/// defense 6s once; Shred adds one extra wound per unmodified 1 to block.
fn roll_defense(
    rending_hits: u32,
    normal_hits: u32,
    defense_target: u8,
    weapon: &Weapon,
) -> (u32, u32) {
    let has_bane = weapon.special_rules.contains(&SpecialRule::Bane);
    let has_shred = weapon.special_rules.contains(&SpecialRule::Shred);

    let mut blocked = 0u32;
    let mut shred_wounds = 0u32;

    if rending_hits > 0 {
        let rending_target = defense_target.saturating_add(4).min(6);
        let mut rolls = dice::roll_d6s(rending_hits, 0);
        if has_bane {
            reroll_sixes(&mut rolls);
        }
        blocked = blocked.saturating_add(dice::count_successes(&rolls, rending_target));
        if has_shred {
            shred_wounds = shred_wounds.saturating_add(count_ones(&rolls));
        }
    }

    if normal_hits > 0 {
        let mut rolls = dice::roll_d6s(normal_hits, 0);
        if has_bane {
            reroll_sixes(&mut rolls);
        }
        blocked = blocked.saturating_add(dice::count_successes(&rolls, defense_target));
        if has_shred {
            shred_wounds = shred_wounds.saturating_add(count_ones(&rolls));
        }
    }

    (blocked, shred_wounds)
}

/// Bane: reroll unmodified defense 6s once; the new result stands.
fn reroll_sixes(rolls: &mut [dice::DieRoll]) {
    for roll in rolls.iter_mut().filter(|r| r.raw == 6) {
        *roll = dice::roll_d6(0);
    }
}

/// Count unmodified 1s (used by Shred).
fn count_ones(rolls: &[dice::DieRoll]) -> u32 {
    rolls
        .iter()
        .filter(|r| r.is_unmodified_one())
        .count()
        .try_into()
        .unwrap_or(u32::MAX)
}

/// Apply defender Regeneration. Returns `(net_wounds, regenerated_count)`.
/// `weapon_rules` are the attacking weapon's rules; Bane/Rending/
/// Unstoppable skip regeneration entirely.
fn apply_regeneration(wounds: u32, defender: &Unit, weapon_rules: &[SpecialRule]) -> (u32, u32) {
    // If the weapon ignores regeneration, skip entirely
    let ignores_regen = weapon_rules.iter().any(SpecialRule::ignores_regeneration);

    if ignores_regen || !defender.has_regeneration() {
        return (wounds, 0);
    }

    // Regeneration: 5+ to ignore each wound
    let regen_rolls = dice::roll_d6s(wounds, 0);
    let ignored = dice::count_successes(&regen_rolls, 5);
    let net = wounds.saturating_sub(ignored);
    (net, ignored)
}

/// Resolve Impact(X): on a charge, roll X dice per model; each 2+ is a hit.
/// Impact hits have no AP/Deadly, are blocked at the defender's normal
/// defense value, and are subject to the defender's Regeneration.
fn resolve_impact(attacker: &Unit, defender: &Unit) -> Option<AttackResult> {
    let x = attacker
        .special_rules
        .iter()
        .find_map(SpecialRule::impact_dice)?;
    let dice_count = u32::from(x).saturating_mul(u32::from(attacker.quantity));
    let rolls = dice::roll_d6s(dice_count, 0);
    let hits = dice::count_successes(&rolls, 2);
    let defense_target = defender.defense.clamp(2, 6);
    let defense_rolls = dice::roll_d6s(hits, 0);
    let blocked = dice::count_successes(&defense_rolls, defense_target);
    let wounds = hits.saturating_sub(blocked);
    let (net_wounds, regenerated) = apply_regeneration(wounds, defender, &[]);
    Some(AttackResult {
        weapon_name: "Impact".to_string(),
        base_attacks: dice_count,
        hits_before_multiplier: hits,
        total_hits: hits,
        blocked_hits: blocked,
        wounds_inflicted: wounds,
        regenerated_wounds: regenerated,
        net_wounds,
        ..AttackResult::default()
    })
}

/// Compute how many models are removed given net wounds and tough values.
fn compute_models_removed(defender: &Unit, net_wounds: u32) -> u32 {
    let tough = defender.effective_tough();
    if tough == 0 {
        return 0;
    }
    net_wounds.checked_div(u32::from(tough)).unwrap_or(0)
}

