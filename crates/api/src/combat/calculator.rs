    #[test]
    fn test_unit_level_furious_generates_extra_hits_on_charge() {
        // Furious granted at unit level (e.g. via Combat Bio-Engineer upgrade)
        // must generate extra hits on unmodified 6s during a melee charge.
        let attacker = Unit::new("Charger", 5, 3, 3)
            .with_rule(SpecialRule::Furious)
            .with_weapon(Weapon::melee("Claws", 5, 2));
        let defender = Unit::new("Target", 5, 3, 4);

        let context = CombatContext::melee_charge();

        // Over 200 resolutions of 10 attacks, the chance of never rolling a
        // single 6 is negligible (~0.997^2000), so extras must appear.
        let mut saw_extras = false;
        for _ in 0..200 {
            let result =
                resolve_attack(&attacker, &defender, &context).expect("resolution succeeds");
            let attack = result.attacks.first().expect("one weapon");
            if attack.extra_attacks > 0 {
                saw_extras = true;
                break;
            }
        }
        assert!(
            saw_extras,
            "unit-level Furious should generate extra hits on unmodified 6s when charging"
        );
    }

